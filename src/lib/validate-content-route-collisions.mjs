import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createMarkdownProcessor, parseFrontmatter } from '@astrojs/markdown-remark';
import remarkMath from 'remark-math';
import { locales } from '../i18n/config.ts';
import { remarkEditorialSafety } from './remark-editorial-safety.mjs';

const projectRoot = fileURLToPath(new URL('../..', import.meta.url));
const defaultContentDir = resolve(projectRoot, 'src', 'content');
const editorialCollections = ['articles', 'sounds'];
let editorialLinkRenderer;

// Matches Astro's getStaticPaths parameter handling for a single dynamic slug.
const publicRouteSlug = (slug) => slug
  .replace(/^\/|\/$/g, '')
  .normalize()
  .replace(/#/g, '%23')
  .replace(/\?/g, '%3F');

const editorialRoute = (collection, locale, slug) => {
  const segment = locale === 'de'
    ? collection === 'articles' ? 'artikel' : 'alltagsgeraeusche'
    : collection;
  return `${locale === 'de' ? '/de' : ''}/${segment}/${publicRouteSlug(slug)}/`;
};

const normalizedRoute = (route) => `${route.split(/[?#]/, 1)[0].replace(/\/+$/, '')}/`;

const linkedEditorialRoutes = async (content) => {
  editorialLinkRenderer ??= await createMarkdownProcessor({
    syntaxHighlight: false,
    remarkPlugins: [remarkEditorialSafety, remarkMath],
  });
  const { metadata } = await editorialLinkRenderer.render(content);
  return metadata.frontmatter.linkedRoutes ?? [];
};

const markdownFiles = (directory) => {
  const files = [];
  for (const locale of locales) {
    const localeDirectory = join(directory, locale);
    if (!existsSync(localeDirectory)) continue;
    for (const entry of readdirSync(localeDirectory, { withFileTypes: true })) {
      if (entry.name.startsWith('.') || !entry.isFile() || !entry.name.endsWith('.md')) continue;
      files.push(join(localeDirectory, entry.name));
    }
  }
  return files;
};

/**
 * @param {{ contentDir?: string }} [options]
 */
export const readEditorialEntries = ({ contentDir = defaultContentDir } = {}) => {
  const entries = [];
  for (const collection of editorialCollections) {
    const collectionDir = join(contentDir, collection);
    for (const sourcePath of markdownFiles(collectionDir).sort()) {
      const source = readFileSync(sourcePath, 'utf8');
      const { frontmatter, content } = parseFrontmatter(source);
      if (typeof frontmatter.locale !== 'string' || typeof frontmatter.slug !== 'string') continue;
      entries.push({
        collection,
        locale: frontmatter.locale,
        sourceSlug: frontmatter.slug,
        slug: publicRouteSlug(frontmatter.slug),
        translationKey: typeof frontmatter.translationKey === 'string' ? frontmatter.translationKey : undefined,
        route: editorialRoute(collection, frontmatter.locale, frontmatter.slug),
        draft: frontmatter.draft === true,
        sourcePath: relative(contentDir, sourcePath).replaceAll('\\', '/'),
        content,
      });
    }
  }
  return entries;
};

/**
 * Finds duplicate IDs generated by the editorial glob loaders before Astro can
 * overwrite an earlier entry with the later file.
 *
 * @param {{ contentDir?: string, entries?: ReturnType<typeof readEditorialEntries> }} [options]
 */
export const findEditorialRouteCollisions = ({ contentDir = defaultContentDir, entries = readEditorialEntries({ contentDir }) } = {}) => {
  const entriesById = new Map();

  for (const entry of entries) {
    const id = `${entry.collection}\u0000${entry.locale}\u0000${entry.slug}`;
    const sourcePaths = entriesById.get(id) ?? [];
    sourcePaths.push(entry.sourcePath);
    entriesById.set(id, sourcePaths);
  }

  return [...entriesById]
    .filter(([, sourcePaths]) => sourcePaths.length > 1)
    .map(([id, sourcePaths]) => {
      const [collection, locale, slug] = id.split('\u0000');
      return { collection, locale, slug, sourcePaths };
    });
};

/**
 * @param {{ contentDir?: string, entries?: ReturnType<typeof readEditorialEntries> }} [options]
 */
export const validateEditorialRouteCollisions = (options) => {
  const collisions = findEditorialRouteCollisions(options);
  if (collisions.length === 0) return;

  const details = collisions.map(({ collection, locale, slug, sourcePaths }) =>
    `- ${collection}/${locale}/${slug}: ${sourcePaths.join(', ')}`).join('\n');
  throw new Error(`[content-route-collision] Duplicate editorial loader IDs or public route parameters would overwrite or collide during loading:\n${details}`);
};

/**
 * Rejects ambiguous editorial translation identities while allowing the
 * intended one-entry-per-locale translation pair within a collection.
 *
 * @param {{ contentDir?: string, entries?: ReturnType<typeof readEditorialEntries> }} [options]
 */
export const validateEditorialTranslationKeyCollisions = ({
  contentDir = defaultContentDir,
  entries = readEditorialEntries({ contentDir }),
} = {}) => {
  const entriesByKey = new Map();
  const entriesByKeyCollectionLocale = new Map();

  for (const entry of entries) {
    if (typeof entry.translationKey !== 'string') continue;
    const keyEntries = entriesByKey.get(entry.translationKey) ?? [];
    keyEntries.push(entry);
    entriesByKey.set(entry.translationKey, keyEntries);

    const identity = `${entry.translationKey}\u0000${entry.collection}\u0000${entry.locale}`;
    const identityEntries = entriesByKeyCollectionLocale.get(identity) ?? [];
    identityEntries.push(entry);
    entriesByKeyCollectionLocale.set(identity, identityEntries);
  }

  const crossCollectionCollisions = [...entriesByKey]
    .filter(([, keyEntries]) => new Set(keyEntries.map((entry) => entry.collection)).size > 1)
    .map(([translationKey, keyEntries]) => ({ translationKey, sourcePaths: keyEntries.map((entry) => entry.sourcePath) }));
  const sameLocaleCollisions = [...entriesByKeyCollectionLocale]
    .filter(([, identityEntries]) => identityEntries.length > 1)
    .map(([identity, identityEntries]) => {
      const [translationKey, collection, locale] = identity.split('\u0000');
      return { translationKey, collection, locale, sourcePaths: identityEntries.map((entry) => entry.sourcePath) };
    });

  if (crossCollectionCollisions.length === 0 && sameLocaleCollisions.length === 0) return;

  const details = [
    ...crossCollectionCollisions.map(({ translationKey, sourcePaths }) =>
      `- translationKey ${translationKey} appears in multiple editorial collections: ${sourcePaths.join(', ')}`),
    ...sameLocaleCollisions.map(({ translationKey, collection, locale, sourcePaths }) =>
      `- translationKey ${translationKey} has multiple ${collection}/${locale} entries: ${sourcePaths.join(', ')}`),
  ].join('\n');
  throw new Error(`[editorial-translation-key-collision] Editorial translation keys must be unique per collection and locale, and cannot span collections:\n${details}`);
};

/**
 * Rejects public references to an editorial entry that is intentionally not
 * generated because its frontmatter marks it as a draft.
 *
 * @param {{ contentDir?: string, entries?: ReturnType<typeof readEditorialEntries>, contentTranslations?: Array<{ collection: string, en: string, de: string }>, soundEntries?: Array<{ locale?: string, translationKey?: string, slug?: string, articleRoute?: string }>, registrySource?: string, soundDataSource?: string }} [options]
 */
export const validateEditorialPublicationIntegrity = async ({
  contentDir = defaultContentDir,
  entries = readEditorialEntries({ contentDir }),
  contentTranslations = [],
  soundEntries = [],
  registrySource = 'src/i18n/routes.ts',
  soundDataSource = 'src/data/sounds.ts',
} = {}) => {
  const draftsByRoute = new Map(entries.filter((entry) => entry.draft).map((entry) => [entry.route, entry]));

  const references = [];
  const addReference = (sourcePath, route) => {
    const draft = draftsByRoute.get(normalizedRoute(route));
    if (draft) references.push({ sourcePath, route: draft.route, draftSource: draft.sourcePath });
  };

  for (const translation of contentTranslations) {
    addReference(registrySource, editorialRoute(translation.collection, 'en', translation.en));
    addReference(registrySource, editorialRoute(translation.collection, 'de', translation.de));
  }
  for (const sound of soundEntries) {
    if (typeof sound.articleRoute === 'string') addReference(soundDataSource, sound.articleRoute);
  }
  for (const entry of entries) {
    if (entry.draft) continue;
    for (const route of await linkedEditorialRoutes(entry.content)) addReference(entry.sourcePath, route);
  }

  if (references.length > 0) {
    const details = references.map(({ sourcePath, route, draftSource }) =>
      `- ${sourcePath} references draft route ${route} (${draftSource})`).join('\n');
    throw new Error(`[editorial-publication-integrity] Draft editorial content is still publicly referenced:\n${details}`);
  }

  const liveGuides = entries.filter((entry) => entry.collection === 'sounds' && !entry.draft);
  const guidesWithoutTranslationKey = liveGuides.filter((entry) =>
    typeof entry.translationKey !== 'string' || entry.translationKey.length === 0);
  if (guidesWithoutTranslationKey.length > 0) {
    const details = guidesWithoutTranslationKey.map((entry) =>
      `- ${entry.sourcePath} is published at ${entry.route} without a translationKey`).join('\n');
    throw new Error(`[sound-guide-publication-integrity] Published sound Markdown must declare a translationKey:\n${details}`);
  }
  const identityFor = (entry) => `${entry.locale}\u0000${entry.translationKey}`;
  const guidesByIdentity = new Map(liveGuides.map((entry) => [identityFor(entry), entry]));
  const guideGateIssues = [];
  const soundDataByIdentity = new Map();
  for (const sound of soundEntries.filter((entry) =>
    typeof entry.locale === 'string' && typeof entry.translationKey === 'string')) {
    const identity = identityFor(sound);
    if (soundDataByIdentity.has(identity)) {
      guideGateIssues.push(`- ${soundDataSource} has duplicate identity ${sound.locale}/${sound.translationKey}`);
      continue;
    }
    soundDataByIdentity.set(identity, sound);
  }

  for (const sound of soundDataByIdentity.values()) {
    if (typeof sound.articleRoute !== 'string') continue;
    const guide = guidesByIdentity.get(identityFor(sound));
    if (!guide) {
      guideGateIssues.push(`- ${soundDataSource} links ${sound.locale}/${sound.translationKey} to ${sound.articleRoute}, but no published sound Markdown exists`);
    } else if (normalizedRoute(sound.articleRoute) !== guide.route) {
      guideGateIssues.push(`- ${soundDataSource} links ${sound.locale}/${sound.translationKey} to ${sound.articleRoute}, but its published route is ${guide.route}`);
    } else if (sound.slug !== guide.sourceSlug) {
      guideGateIssues.push(`- ${soundDataSource} exposes ${sound.locale}/${sound.translationKey} with slug ${sound.slug ?? '(missing)'}, but its published slug is ${guide.sourceSlug}`);
    }
  }

  for (const guide of liveGuides) {
    const sound = soundDataByIdentity.get(identityFor(guide));
    if (!sound || typeof sound.articleRoute !== 'string') {
      guideGateIssues.push(`- ${guide.sourcePath} is published at ${guide.route}, but ${soundDataSource} does not expose its guide link`);
    }
  }

  if (guideGateIssues.length > 0) {
    throw new Error(`[sound-guide-publication-integrity] Published sound Markdown and Explorer guide links must agree:\n${guideGateIssues.join('\n')}`);
  }
};
